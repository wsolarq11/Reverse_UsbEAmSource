#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""查询 usbeam 分析索引（只读出口）。

前提：先跑 `python tools/index/build_index.py`。

用法：
  python tools/index/q.py stats
  python tools/index/q.py missing [--top N]        # 未落地清单（唯一数字源）
  python tools/index/q.py gap [--top N]            # 按文件的待还原分布
  python tools/index/q.py landed <marker>          # S / S-inline / S-eq / S-sig / P
  python tools/index/q.py func <name片段|0xVA>      # 单函数证据包
  python tools/index/q.py sql "SELECT ..."         # 只读逃生舱

口径：
  缺口判定的唯一实现在 `tools/index/common.py`（`func_key` / `is_generated` /
  `is_never_land` / `classify_missing`）。`node tools/list_missing.js` 是本脚本
  `missing` 的薄封装，两者输出必须逐元素一致。
"""

import argparse
import sqlite3
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import common  # noqa: E402

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

# 已实现判定：蓝图键在 backend 实现键集合里。只做精确相等，不做短名回退——
# 短名回退会把「别的类型里的同名方法」算成本函数的实现。
IMPL_EXPR = "EXISTS(SELECT 1 FROM impl_key i WHERE i.key = b.func_key)"

# 资产命中判定：资产名归一化键 == 蓝图短名（小写）。
ASM_EXPR = "EXISTS(SELECT 1 FROM asset a WHERE a.norm = b.func_short_lc)"

BLUEPRINT_SQL = """
SELECT b.file, b.func, b.func_key, b.func_short, b.func_short_lc
FROM blueprint b
WHERE b.file <> '<autogenerated>'
"""


def connect():
    if not common.DB_PATH.is_file():
        sys.exit("索引不存在，先跑：python tools/index/build_index.py")
    conn = sqlite3.connect("file:%s?mode=ro" % common.DB_PATH.as_posix(), uri=True)
    conn.row_factory = sqlite3.Row
    return conn


def cmd_stats(conn):
    for table in ("symbol", "blueprint", "landed", "impl_key", "asset", "method_size"):
        n = conn.execute("SELECT count(*) FROM %s" % table).fetchone()[0]
        print("%-12s %d" % (table, n))
    rows = conn.execute("SELECT marker, count(*) n FROM landed GROUP BY marker ORDER BY n DESC").fetchall()
    print("标记分布：" + "  ".join("%s=%d" % (r["marker"] or "UNMARKED", r["n"]) for r in rows))


def _sizes(conn):
    """→ (by_key, by_short)，值均为 (VA, 字节数)。

    长度优先取 `va_map_fixed2.txt` 的实测值（并入短名表），缺失时用符号表里
    「下一个符号 VA − 本 VA」作上界（与退役的 tools/p_funcs.py 同算法）。只靠
    method_size 会有一大片函数拿不到长度，因为那张表只有 458 条。

    键分两级：`by_key` 用完整比较键（唯一）；`by_short` 用短名（**会撞车**——
    不同类型可以有同名方法，例如多个 `Hide`），只作回退，不可当准。
    """
    by_key, by_short = {}, {}
    rows = conn.execute("SELECT va, name FROM symbol ORDER BY va").fetchall()
    for i, r in enumerate(rows):
        if not r["name"].startswith("main."):
            continue
        key = common.func_key(r["name"])
        nxt = rows[i + 1]["va"] if i + 1 < len(rows) else r["va"] + 0x200
        entry = (r["va"], nxt - r["va"])
        by_key[key] = entry
        by_short.setdefault(common.func_short_of(key), entry)
    for r in conn.execute("SELECT name, va, size FROM method_size"):
        by_short[r["name"]] = (r["va"], r["size"])
    return by_key, by_short


def _lookup(by_key, by_short, key):
    """先按完整比较键取长度，再退回短名。"""
    if key and key in by_key:
        return by_key[key]
    return by_short.get(common.func_short_of(key or ""), (0, 0))


def _impl_keys(conn):
    """backend 侧已实现键集合。"""
    return {r[0] for r in conn.execute("SELECT key FROM impl_key")}


def _asset_norms(conn):
    """磁盘资产归一化键集合（小写短名形态）。"""
    return {r[0] for r in conn.execute("SELECT norm FROM asset")}


def _classify(conn, impl=None):
    """按蓝图逐条分类，返回 {reason: [row]}。唯一缺失判定的读侧实现。"""
    if impl is None:
        impl = _impl_keys(conn)
    buckets = {"MISSING": [], "GEN": [], "NEVER": []}
    for r in conn.execute(BLUEPRINT_SQL):
        if r["func_key"] in impl:
            continue
        if common.is_generated(r["func_key"]):
            reason = "GEN"
        elif common.is_never_land(r["func_key"]):
            reason = "NEVER"
        else:
            reason = "MISSING"
        buckets[reason].append(r)
    return buckets


def cmd_missing(conn, top):
    buckets = _classify(conn)
    by_key, by_short = _sizes(conn)
    assets = _asset_norms(conn)
    missing = buckets["MISSING"]
    with_asm = [r for r in missing if r["func_short_lc"] in assets]
    print("未落地（需人工还原）: %d" % len(missing))
    print("  其中 有反汇编资产  : %d" % len(with_asm))
    print("已排除 编译器生成物  : %d" % len(buckets["GEN"]))
    print("已排除 永不落地名单  : %d" % len(buckets["NEVER"]))
    print("=== 最小 %d 个（按方法字节数）===" % top)
    sized = [(r, _lookup(by_key, by_short, r["func_key"])) for r in missing]
    for r, (va, size) in sorted(sized, key=lambda p: p[1][1] or (1 << 30))[:top]:
        print("  %5sB  0x%010x  %s" % (size or "-", va, r["func_key"]))


def cmd_gap(conn, top):
    """按文件的待还原分布：只统计需人工还原的 MISSING。"""
    impl = _impl_keys(conn)
    buckets = _classify(conn, impl)
    assets = _asset_norms(conn)
    agg = {}
    for r in conn.execute(BLUEPRINT_SQL):
        a = agg.setdefault(r["file"], [0, 0, 0, 0])
        a[0] += 1
        if r["func_key"] in impl:
            a[1] += 1
    for r in buckets["MISSING"]:
        a = agg[r["file"]]
        a[2] += 1
        if r["func_short_lc"] in assets:
            a[3] += 1
    rows = sorted(((f, v) for f, v in agg.items() if v[2] > 0),
                  key=lambda kv: (-kv[1][3], -kv[1][2]))
    print("%-42s %6s %6s %7s %8s" % ("file", "蓝图", "已实现", "待还原", "有asm资产"))
    print("-" * 76)
    for f, v in rows[:top] if top else rows:
        print("%-42s %6d %6d %7d %8d" % (f, v[0], v[1], v[2], v[3]))
    print("-" * 76)
    print("文件 %d 个；待还原 %d，其中有 asm 资产 %d" % (
        len(rows), sum(v[2] for _f, v in rows), sum(v[3] for _f, v in rows)))


def cmd_landed(conn, marker):
    """按档位列已落地函数，附符号 VA 与实测字节数（取代 tools/p_funcs.py 的 CSV 视图）。"""
    by_key, by_short = _sizes(conn)
    rows = conn.execute(
        "SELECT file, line, func_sig, impl_key, impl_short FROM landed"
        " WHERE marker = ? ORDER BY file, line", (marker,)).fetchall()
    for r in rows:
        va, size = _lookup(by_key, by_short, r["impl_key"])
        print("%-40s %5d  %-12s %6s  %s" % (
            r["file"], r["line"], ("0x%x" % va) if va else "-", size or "-", r["func_sig"][:58]))
    print("共 %d 条 [%s]" % (len(rows), marker))


def cmd_func(conn, needle):
    if needle.lower().startswith("0x"):
        hits = conn.execute("SELECT * FROM symbol WHERE va = ?", (int(needle, 16),)).fetchall()
    else:
        hits = conn.execute(
            "SELECT * FROM symbol WHERE name LIKE ? ORDER BY va LIMIT 20",
            ("%" + needle + "%",)).fetchall()
    if not hits:
        print("符号表无命中")
        return
    for h in hits:
        name, va = h["name"], h["va"]
        key = common.resolve_func_key(name)
        short = common.func_short_of(key).lower()
        print("=" * 78)
        print("符号  0x%x  %s" % (va, name))
        print("键    %s" % key)
        for b in conn.execute(
                "SELECT * FROM blueprint WHERE func_key = ? OR func_short = ? LIMIT 3",
                (key, common.func_short_of(key))).fetchall():
            print("蓝图  %s  %s  行 %d-%d (%d 行)" % (
                b["file"], b["func"], b["start_line"], b["end_line"], b["nlines"]))
        for l in conn.execute(
                "SELECT * FROM landed WHERE impl_key = ? OR impl_short = ? LIMIT 5",
                (key, common.func_short_of(key))).fetchall():
            print("落地  %s:%d  [%s]  %s" % (
                l["file"], l["line"], l["marker"] or "UNMARKED", l["func_sig"][:60]))
        for m in conn.execute("SELECT * FROM method_size WHERE name = ?",
                              (common.func_short_of(key),)).fetchall():
            print("尺寸  0x%x  %d 字节（va_map_fixed2）" % (m["va"], m["size"]))
        asm = conn.execute(
            "SELECT path FROM asset WHERE norm = ?"
            " OR (length(norm) >= 6 AND length(?) >= 6 AND (instr(norm, ?) > 0 OR instr(?, norm) > 0))"
            " ORDER BY CASE WHEN norm = ? THEN 0 ELSE 1 END, length(norm) LIMIT 8",
            (short, short, short, short, short)).fetchall()
        for a in asm:
            print("资产  %s" % a["path"])


def cmd_sql(conn, query):
    if not query.strip().lower().startswith(("select", "with", "pragma")):
        sys.exit("只允许 SELECT / WITH / PRAGMA")
    rows = conn.execute(query).fetchall()
    if not rows:
        print("(空)")
        return
    print(" | ".join(rows[0].keys()))
    for r in rows[:200]:
        print(" | ".join("" if v is None else str(v) for v in tuple(r)))
    if len(rows) > 200:
        print("...(共 %d 行)" % len(rows))


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("stats")
    p_missing = sub.add_parser("missing")
    p_missing.add_argument("--top", type=int, default=40)
    p_gap = sub.add_parser("gap")
    p_gap.add_argument("--top", type=int, default=30)
    p_ld = sub.add_parser("landed"); p_ld.add_argument("marker")
    p_fn = sub.add_parser("func"); p_fn.add_argument("needle")
    p_sql = sub.add_parser("sql"); p_sql.add_argument("query")
    args = ap.parse_args()

    conn = connect()
    if args.cmd == "stats":
        cmd_stats(conn)
    elif args.cmd == "missing":
        cmd_missing(conn, args.top)
    elif args.cmd == "gap":
        cmd_gap(conn, args.top)
    elif args.cmd == "landed":
        cmd_landed(conn, args.marker)
    elif args.cmd == "func":
        cmd_func(conn, args.needle)
    else:
        cmd_sql(conn, args.query)


if __name__ == "__main__":
    main()
